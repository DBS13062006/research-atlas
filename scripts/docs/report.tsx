// pnpm docs:report — builds docs/report/report.md from docs/report/report.src.md and prints it to
// docs/report/report.pdf through Chromium.
//   @include ../05-ddl.md#5.2 Named constraints level=2   copies that section of a chapter (heading
//                                                           prefix match, re-levelled, links rebased)
//   @git-stats                                             commit statistics from this repository
// Generated numbers and outputs therefore come from the chapters, which come from the live database.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { chromium } from "@playwright/test";
import { renderToStaticMarkup } from "react-dom/server";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { createHighlighter } from "shiki";

const REPORT_DIR = resolve("docs/report");
const SOURCE = join(REPORT_DIR, "report.src.md");

function section(file: string, prefix: string, level: number | null): string {
  // The chapter navigation footer belongs to the web docs, not the report.
  const lines = readFileSync(file, "utf8").split("<!-- chapter-nav -->")[0].split("\n");
  const start = lines.findIndex((l) => /^#{1,6} /.test(l) && l.replace(/^#+ /, "").startsWith(prefix));
  if (start === -1) throw new Error(`${file}: no heading starting with "${prefix}"`);
  const own = lines[start].match(/^#+/)?.[0].length ?? 1;
  let end = lines.length;
  let fence = false;
  for (let i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith("```")) fence = !fence;
    const m = !fence && lines[i].match(/^(#+) /);
    if (m && m[1].length <= own) {
      end = i;
      break;
    }
  }
  const shift = level === null ? 0 : level - own;
  let inFence = false;
  const body = lines.slice(start, end).map((l) => {
    if (l.startsWith("```")) inFence = !inFence;
    if (inFence || !/^#+ /.test(l)) return l;
    const n = Math.min(6, Math.max(1, (l.match(/^#+/)?.[0].length ?? 1) + shift));
    // Chapter numbers ("4.1 Method") would clash with the report's own numbering.
    return `${"#".repeat(n)}${l.replace(/^#+/, "").replace(/^ \d+(\.\d+)+ /, " ")}`;
  });
  // Rebase relative links and images from the chapter's folder to the report's folder.
  const from = dirname(file);
  return body
    .join("\n")
    .replace(/(!?\[[^\]]*\]\()([^)\s]+)(\))/g, (all, open: string, href: string, close: string) => {
      if (/^(https?:|mailto:|#|\/)/.test(href)) return all;
      return `${open}${relative(REPORT_DIR, resolve(from, href))}${close}`;
    })
    .trim();
}

function gitStats(): string {
  const git = (...args: string[]) => execFileSync("git", args, { encoding: "utf8" }).trim();
  const count = git("rev-list", "--count", "HEAD");
  const first = git("log", "--reverse", "--format=%ad", "--date=short").split("\n")[0];
  const last = git("log", "-1", "--format=%ad", "--date=short");
  const authors = git("shortlog", "-sn", "HEAD")
    .split("\n")
    .map((l) => l.trim().split(/\s+(.+)/));
  const types = new Map<string, number>();
  for (const subject of git("log", "--format=%s").split("\n")) {
    const type = subject.match(/^(\w+)(\(|:)/)?.[1] ?? "other";
    types.set(type, (types.get(type) ?? 0) + 1);
  }
  return [
    `${count} commits between ${first} and ${last}, every one on \`main\` and pushed to GitHub, each`,
    "checked by the CI workflow.",
    "",
    "| Author | Commits |",
    "| --- | --- |",
    ...authors.map(([n, name]) => `| ${name} | ${n} |`),
    "",
    "| Commit type | Count |",
    "| --- | --- |",
    ...[...types.entries()].sort((a, b) => b[1] - a[1]).map(([t, n]) => `| \`${t}\` | ${n} |`),
  ].join("\n");
}

function build(): string {
  const out: string[] = [];
  for (const line of readFileSync(SOURCE, "utf8").split("\n")) {
    const inc = line.match(/^@include (\S+?)#(.+?)(?: level=(\d))?\s*$/);
    if (inc) out.push(section(resolve(REPORT_DIR, inc[1]), inc[2].trim(), inc[3] ? Number(inc[3]) : null));
    else if (line.trim() === "@git-stats") out.push(gitStats());
    else out.push(line);
  }
  return out.join("\n");
}

const decodeEntities = (s: string) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#x27;/g, "'")
    .replace(/&amp;/g, "&");

async function main(): Promise<void> {
  const markdown = build();
  const header = [
    "<!-- Generated by pnpm docs:report from report.src.md and the chapters in docs/. Do not edit by hand. -->",
    "",
  ].join("\n");
  writeFileSync(join(REPORT_DIR, "report.md"), header + markdown);

  // Cover page and contents come from the front matter block; the body is rendered Markdown.
  const [cover, body] = markdown.split(/^@body$/m);
  let html = renderToStaticMarkup(<ReactMarkdown remarkPlugins={[remarkGfm]}>{body}</ReactMarkdown>);
  const highlighter = await createHighlighter({
    themes: ["github-light-default"],
    langs: ["sql", "cypher", "json", "http", "text", "bash"],
  });
  html = html.replace(
    /<pre><code class="language-(sql|cypher|json|http|bash)">([\s\S]*?)<\/code><\/pre>/g,
    (_all, lang: string, code: string) =>
      highlighter.codeToHtml(decodeEntities(code).replace(/\n$/, ""), {
        lang,
        theme: "github-light-default",
      }),
  );
  html = html.replace(
    /<pre><code class="language-mermaid">([\s\S]*?)<\/code><\/pre>/g,
    '<pre class="mermaid">$1</pre>',
  );
  const sections = [...body.matchAll(/^# (.+)$/gm)].map((m) => m[1]);
  const coverHtml = renderToStaticMarkup(<ReactMarkdown remarkPlugins={[remarkGfm]}>{cover}</ReactMarkdown>);
  const page = `<!doctype html><html><head><meta charset="utf-8"><base href="file://${REPORT_DIR}/">
<style>
  @page { size: A4; margin: 18mm 16mm 20mm; }
  body { font: 10pt/1.5 "Helvetica Neue", Arial, sans-serif; color: #1c2230; }
  h1, h2, h3 { font-family: Georgia, "Times New Roman", serif; font-weight: 400; color: #101828; }
  h1 { font-size: 21pt; margin: 22pt 0 10pt; border-bottom: 1px solid #c9ced8; padding-bottom: 4pt; break-after: avoid; }
  .toc + h1 { break-before: page; }
  h2 { font-size: 14pt; margin: 16pt 0 6pt; break-after: avoid; }
  h3 { font-size: 11.5pt; margin: 12pt 0 4pt; break-after: avoid; }
  h4 { font-size: 10pt; margin: 10pt 0 4pt; }
  p, li { orphans: 3; widows: 3; }
  a { color: #1d4ed8; text-decoration: none; }
  table { border-collapse: collapse; width: 100%; font-size: 7.6pt; margin: 6pt 0 10pt; break-inside: auto; }
  tr { break-inside: avoid; }
  th, td { border: 1px solid #d6dae2; padding: 2.5pt 4pt; text-align: left; vertical-align: top; }
  th { background: #eef1f6; font-weight: 600; }
  code { font: 8pt Menlo, Consolas, monospace; background: #f2f4f8; padding: 0 2pt; border-radius: 2pt; }
  pre, pre.shiki { font: 7.6pt/1.45 Menlo, Consolas, monospace; background: #f6f8fa !important; border: 1px solid #e1e5eb;
        padding: 6pt 8pt; white-space: pre-wrap; word-break: break-word; border-radius: 3pt; break-inside: avoid; }
  pre code { background: none; padding: 0; font-size: inherit; }
  img { max-width: 100%; max-height: 135mm; display: block; margin: 6pt auto 2pt; border: 1px solid #e1e5eb; }
  pre.mermaid { background: none !important; border: none; text-align: center; }
  img[src*="er/"], img[src*="schema/"] { max-height: 225mm; border: none; }
  img[src*="screenshots/"] { display: inline-block; box-sizing: border-box; width: 48%; margin: 0.5% 0.8%; }
  img[src*="assets/ddl/"] { max-height: 92mm; }
  img[src*="assets/lab-"] { max-height: 120mm; }
  .cover { height: 250mm; display: flex; flex-direction: column; justify-content: center; text-align: center; }
  .cover h1 { break-before: auto; border: none; font-size: 30pt; margin-bottom: 4pt; }
  .cover table { width: 70%; margin: 18pt auto; font-size: 10pt; }
  .toc { break-before: page; }
  .toc h1 { break-before: auto; }
  .toc ol { columns: 1; font-size: 11pt; line-height: 1.9; }
  blockquote { margin: 6pt 0; padding: 4pt 10pt; border-left: 3px solid #c9a13b; color: #3c4456; background: #faf7ef; }
</style></head><body>
<section class="cover">${coverHtml}</section>
<section class="toc"><h1>Contents</h1><ol>${sections.map((s) => `<li>${s.replace(/^\d+\.?\s*/, "")}</li>`).join("")}</ol></section>
${html}
</body></html>`;
  const htmlFile = join(tmpdir(), "research-atlas-report.html");
  writeFileSync(htmlFile, page);

  const browser = await chromium.launch();
  try {
    const tab = await browser.newPage();
    await tab.goto(`file://${htmlFile}`, { waitUntil: "load" });
    if (html.includes('class="mermaid"')) {
      await tab.addScriptTag({ path: resolve("node_modules/mermaid/dist/mermaid.min.js") });
      await tab.evaluate(async () => {
        const m = (
          window as unknown as { mermaid: { initialize: (o: object) => void; run: () => Promise<void> } }
        ).mermaid;
        m.initialize({ startOnLoad: false, theme: "neutral", securityLevel: "strict" });
        await m.run();
      });
    }
    await tab.pdf({
      path: join(REPORT_DIR, "report.pdf"),
      format: "A4",
      printBackground: true,
      displayHeaderFooter: true,
      headerTemplate: "<span></span>",
      footerTemplate:
        '<div style="font:7pt Helvetica,Arial;color:#6b7280;width:100%;padding:0 16mm;display:flex;justify-content:space-between"><span>Research Atlas · DBMS mini-project report</span><span class="pageNumber"></span></div>',
      margin: { top: "16mm", bottom: "18mm", left: "16mm", right: "16mm" },
    });
    const pages = await tab.evaluate(() => document.body.scrollHeight);
    console.log(
      `docs:report wrote report.md and report.pdf (${sections.length} sections, ~${Math.round(pages / 1050)} pages)`,
    );
  } finally {
    await browser.close();
  }
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
